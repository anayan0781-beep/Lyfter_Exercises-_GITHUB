# String + String
print("Hello " + "World")
#Both values are strings, so Python can concatenate (join) them.

# List + List
print([1, 2, 3] + [4, 5, 6])
#Both are lists, so Python joins the two lists together.

# Float + Integer
print(5.5 + 2)
#5.5 is a float and 2 is an integer.
#Python can perform mathematical operations between these numeric types.

# Boolean + Boolean
print(True + False)



# Integer + String
print(10 + " apples")
#unsupported operand type(s) for +: 'int' and 'str'
#10 is an integer and " apples" is a str
